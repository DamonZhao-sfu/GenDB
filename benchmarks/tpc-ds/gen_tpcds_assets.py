#!/usr/bin/env python3
"""Generate all TPC-DS benchmark assets using DuckDB's built-in ``tpcds`` extension.

This is the TPC-DS analogue of TPC-H's ``dbgen`` step. Instead of cloning and
compiling an external C toolkit, it uses DuckDB's self-contained ``tpcds``
extension, which provides:

  * ``CALL dsdgen(sf = <N>)``        -> materializes all 24 TPC-DS tables
  * ``SELECT * FROM tpcds_queries()`` -> the 99 standard queries with the
                                         spec's default parameter substitutions

From those, this script emits everything the GenDB harness needs:

  * ``schema.sql``            CREATE TABLE DDL for all 24 tables (DuckDB dialect),
                              column order matching the exported data files.
  * ``queries.sql``          the 99 queries in GenDB's ``-- Q<N>: ...`` format.
  * ``tables.json``          table metadata (load order + column types), consumed
                              by generate_ground_truth.py and workload.py so they
                              never have to parse SQL.
  * ``data/sf<N>/<table>.tbl`` pipe-delimited data files (same convention as TPC-H).

Requires network access on first run to download the ``tpcds`` extension from
DuckDB's extension repository (``extensions.duckdb.org``).

Usage:
    python3 benchmarks/tpc-ds/gen_tpcds_assets.py --sf 1
    python3 benchmarks/tpc-ds/gen_tpcds_assets.py --sf 10 --data-dir /path/to/out
"""

import argparse
import json
import os
import sys

try:
    import duckdb
except ImportError:
    print("Error: duckdb Python package not found. Install with: pip install duckdb")
    sys.exit(1)


# TPC-DS tables in a foreign-key-safe load order: dimensions first, then facts.
# (DuckDB does not enforce FKs on COPY, but keeping a sane order is cheap and
#  makes the generated schema.sql/data pleasant to read.)
LOAD_ORDER = [
    # dimension / lookup tables
    "call_center",
    "catalog_page",
    "customer_address",
    "customer_demographics",
    "date_dim",
    "household_demographics",
    "income_band",
    "item",
    "promotion",
    "reason",
    "ship_mode",
    "store",
    "time_dim",
    "warehouse",
    "web_page",
    "web_site",
    "customer",
    # fact tables
    "inventory",
    "store_sales",
    "store_returns",
    "catalog_sales",
    "catalog_returns",
    "web_sales",
    "web_returns",
]


def load_extension(con):
    """Install + load the tpcds extension, with a friendly error on failure."""
    try:
        con.execute("INSTALL tpcds;")
        con.execute("LOAD tpcds;")
    except Exception as e:
        print("Error: failed to install/load the DuckDB 'tpcds' extension.")
        print(f"  {e}")
        print(
            "\nThis step needs outbound access to extensions.duckdb.org to fetch\n"
            "the extension the first time. Retry on a machine with open network,\n"
            "or pre-install the extension into ~/.duckdb/extensions."
        )
        sys.exit(1)


def introspect_tables(con):
    """Return {table: [(col_name, col_type), ...]} in DDL/storage column order."""
    tables = {}
    existing = {r[0] for r in con.execute("SHOW TABLES").fetchall()}
    for table in LOAD_ORDER:
        if table not in existing:
            print(f"  Warning: table '{table}' not created by dsdgen, skipping")
            continue
        cols = con.execute(
            """
            SELECT column_name, data_type
            FROM information_schema.columns
            WHERE table_name = ?
            ORDER BY ordinal_position
            """,
            [table],
        ).fetchall()
        tables[table] = [(c[0], c[1]) for c in cols]
    return tables


def write_schema_sql(tables, path):
    """Emit CREATE TABLE DDL. Column order matches the exported .tbl files."""
    lines = [
        "-- TPC-DS Schema (24 tables) — auto-generated by gen_tpcds_assets.py",
        "-- Column order matches the pipe-delimited data files in data/sf<N>/.",
        "-- DuckDB dialect; portable enough for the GenDB ground-truth oracle.",
        "",
    ]
    for table, cols in tables.items():
        lines.append(f"CREATE TABLE {table} (")
        col_lines = [f"    {name:<28} {ctype}" for name, ctype in cols]
        lines.append(",\n".join(col_lines))
        lines.append(");")
        lines.append("")
    with open(path, "w") as f:
        f.write("\n".join(lines))


def write_tables_json(tables, path):
    """Emit machine-readable table metadata (load order + column types)."""
    payload = {
        "load_order": [t for t in LOAD_ORDER if t in tables],
        "columns": {t: [[c, ty] for c, ty in cols] for t, cols in tables.items()},
    }
    with open(path, "w") as f:
        json.dump(payload, f, indent=2)


def write_queries_sql(con, path):
    """Emit the 99 standard queries in GenDB's ``-- Q<N>: ...`` block format."""
    rows = con.execute(
        "SELECT query_nr, query FROM tpcds_queries() ORDER BY query_nr"
    ).fetchall()
    if not rows:
        print("Error: tpcds_queries() returned no rows.")
        sys.exit(1)

    blocks = [
        "-- TPC-DS Standard Queries (Q1–Q99) with default parameter substitutions",
        "-- Auto-generated from DuckDB's tpcds_queries() (TPC-DS spec defaults).",
        "",
    ]
    for query_nr, query in rows:
        sql = (query or "").strip()
        # Normalize to a single trailing semicolon so the parser splits cleanly.
        sql = sql.rstrip().rstrip(";").strip()
        blocks.append(f"-- Q{query_nr}: TPC-DS query {query_nr}")
        blocks.append(sql + ";")
        blocks.append("")
    with open(path, "w") as f:
        f.write("\n".join(blocks))
    return len(rows)


def export_data(con, tables, data_dir):
    """Dump each table to <data_dir>/<table>.tbl as pipe-delimited text."""
    os.makedirs(data_dir, exist_ok=True)
    for table in tables:
        out_path = os.path.join(data_dir, f"{table}.tbl")
        # HEADER false + '|' delimiter mirrors TPC-H .tbl files. NULLs are written
        # as empty fields and read back as NULL by generate_ground_truth.py.
        con.execute(
            f"COPY {table} TO '{out_path}' (FORMAT csv, DELIMITER '|', HEADER false)"
        )
        count = con.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        print(f"  {table}.tbl: {count:,} rows")


def main():
    parser = argparse.ArgumentParser(description="Generate TPC-DS benchmark assets")
    parser.add_argument("--sf", type=int, default=1, help="Scale factor (default: 1)")
    parser.add_argument("--data-dir", type=str, help="Override data output directory")
    parser.add_argument(
        "--skip-data",
        action="store_true",
        help="Only (re)generate schema.sql/queries.sql/tables.json, not data files",
    )
    args = parser.parse_args()

    script_dir = os.path.dirname(os.path.abspath(__file__))
    schema_path = os.path.join(script_dir, "schema.sql")
    queries_path = os.path.join(script_dir, "queries.sql")
    tables_json_path = os.path.join(script_dir, "tables.json")
    data_dir = args.data_dir or os.path.join(script_dir, "data", f"sf{args.sf}")

    print("=== TPC-DS Asset Generation ===")
    print(f"Scale factor:   {args.sf}")
    print(f"Data directory: {data_dir}")

    con = duckdb.connect(":memory:")
    load_extension(con)

    print(f"\nGenerating TPC-DS data at scale factor {args.sf} (dsdgen)...")
    con.execute(f"CALL dsdgen(sf = {args.sf})")

    tables = introspect_tables(con)
    print(f"Created {len(tables)} tables.")

    print("\nWriting schema.sql, tables.json...")
    write_schema_sql(tables, schema_path)
    write_tables_json(tables, tables_json_path)

    print("Writing queries.sql...")
    n_queries = write_queries_sql(con, queries_path)
    print(f"  {n_queries} queries written.")

    if args.skip_data:
        print("\nSkipping data export (--skip-data).")
    else:
        print(f"\nExporting data to {data_dir}...")
        export_data(con, tables, data_dir)

    con.close()
    print("\n=== TPC-DS assets ready ===")
    print(f"  schema.sql   -> {schema_path}")
    print(f"  queries.sql  -> {queries_path}")
    print(f"  tables.json  -> {tables_json_path}")
    if not args.skip_data:
        print(f"  data         -> {data_dir}")


if __name__ == "__main__":
    main()
